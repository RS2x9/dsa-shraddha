/*
    GRAPHS:
    --> It is called as "NETWORK OF NODES" because nodes are connected to each other, there is no hierarchy followed
    --> Nodes are connected to each other by edges as trees were connected by branches
    --> a single node in GRAPHS are known as vertex, multiple are known as vertices
    --> example: 
        --> the "map", or ola , uber shows graphs of roads or any area, they are formed using graph data structure
        --> social media uses graphs to connect multiple people together
        --> Natural Language Processing also uses graphs 
*/

/*
    TYPES OF GRAPHS ON THE BASIS OF EDGES :-
    1. Uni Directional Graph:-
        --> The edge connecting two vertex has a direction: that direction can exists from vertex 1 to 2 or from vertex 2 to 1 
    
    2. Un Directed Graph/ Bi Directed Graph:-
        --> two direction exists: from vertex 1 to 2 and from vertex 2 to 1
*/

/*
    TYPES OF GRAPHS BASED ON THE EDGE WEIGHTS:-
    1. Weighted Graph:- 
        --> there is a value associated with the graph
        --> Ex: two cities are connected by road and the distance between them is 10 km
        --> weights can be either positive or negative 
        --> Ex : the money spent to travell from city to city 
    
    2. Un Weighted Graph:-
        --> Only edges are present between the two vertex, there is no weight associated with it.
*/

/*
    TYPES OF GRAPH BASED ON THE EDGES:-
    1. Undirected - Unweighted
    2. Undirected - Weighted
    3. Directed - Unweighted
    4. Directed - Weighted
*/

/*
    TYPES OF GRAPH BASED ON CONNECTION:-
    1. Connected Graph:-
        --> All the vertex will connected to atleast one of the other vertex

    2. Dis Connected Graph:-
        --> There will be few vertex that will not be connected to any  other vertex
        --> This will called as single graph, just there will be multiple components formed of the same graph
*/